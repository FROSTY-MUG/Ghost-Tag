/**
 * @file keyWrap.ts
 * @summary Cryptographic key wrapping and unwrapping routines.
 *
 * Implements two-tier key hierarchy wrapping:
 * - The Data Encryption Key (DEK) is encrypted with the Key Encryption Key (KEK) using AES-256-GCM.
 * - Authenticated with 19-byte domain separation AAD:
 *   KEY_WRAP_PURPOSE (0x57) || KEY_ID (16B) || KDF_VERSION (2B LE).
 * - Prevents cut-and-paste key substitution across vaults or tag records.
 */

import {
  KEY_WRAP_PURPOSE_BYTE,
  KEY_WRAP_AAD_BYTE_LENGTH,
  KEY_ID_BYTE_LENGTH,
  DEK_BYTE_LENGTH,
  KEK_BYTE_LENGTH,
  KeyStatus,
  WrappedDEK,
} from '../contracts/keyHierarchy';
import {
  GhostTagError,
  GhostTagErrorCode,
  ErrorCategory,
  ErrorSeverity,
} from '../contracts/errors';
import { encrypt, decrypt } from './aesGcm';

/**
 * Converts a byte array to a lowercase hexadecimal string.
 *
 * @param bytes Input byte array.
 * @returns 2-character hex string per byte.
 */
export function bytesToHex(bytes: Uint8Array): string {
  let hex = '';
  for (let i = 0; i < bytes.length; i++) {
    hex += bytes[i].toString(16).padStart(2, '0');
  }
  return hex;
}

/**
 * Converts a hexadecimal string to a Uint8Array.
 *
 * @param hex Hexadecimal string.
 * @returns Decoded Uint8Array.
 * @throws {Error} If hex string has invalid length or character format.
 */
export function hexToBytes(hex: string): Uint8Array {
  const cleanHex = hex.trim();
  if (cleanHex.length % 2 !== 0) {
    throw new Error(`Invalid hexadecimal string length: ${cleanHex.length}`);
  }
  const bytes = new Uint8Array(cleanHex.length / 2);
  for (let i = 0; i < cleanHex.length; i += 2) {
    const val = parseInt(cleanHex.substring(i, i + 2), 16);
    if (Number.isNaN(val)) {
      throw new Error(`Invalid hexadecimal character at position ${i}: "${cleanHex.substring(i, i + 2)}"`);
    }
    bytes[i / 2] = val;
  }
  return bytes;
}

/**
 * Constructs the canonical 19-byte Additional Authenticated Data (AAD) for key wrapping.
 *
 * Layout:
 * KEY_WRAP_PURPOSE (1B: 0x57) || KEY_ID (16B raw) || KDF_VERSION (2B Little-Endian)
 *
 * @param keyId 16-byte unique DEK identifier.
 * @param kdfVersion 16-bit unsigned integer KDF version.
 * @returns 19-byte AAD Uint8Array.
 * @throws {GhostTagError} If keyId length is not 16 bytes.
 */
export function buildKeyWrapAAD(
  keyId: Uint8Array,
  kdfVersion: number
): Uint8Array {
  if (!keyId || keyId.length !== KEY_ID_BYTE_LENGTH) {
    throw new GhostTagError({
      code: GhostTagErrorCode.ARGON2ID_FAILED,
      userMessage: `Key wrap AAD construction requires a ${KEY_ID_BYTE_LENGTH}-byte keyId, received: ${keyId?.length ?? 0} bytes.`,
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.ERROR,
    });
  }

  const aad = new Uint8Array(KEY_WRAP_AAD_BYTE_LENGTH);
  aad[0] = KEY_WRAP_PURPOSE_BYTE;
  aad.set(keyId, 1);

  const view = new DataView(aad.buffer, aad.byteOffset, aad.byteLength);
  view.setUint16(17, kdfVersion & 0xffff, true); // Little-Endian unsigned 16-bit

  return aad;
}

/**
 * Wraps a Data Encryption Key (DEK) under an ephemeral Key Encryption Key (KEK).
 *
 * Security Properties:
 * - Bound to keyId and kdfVersion via AAD.
 * - Always uses a fresh 12-byte nonce generated by encrypt().
 * - Key identifier is stored in lowercase hexadecimal format in the resulting WrappedDEK.
 *
 * @param kek 32-byte Key Encryption Key.
 * @param dek 32-byte Data Encryption Key.
 * @param keyId 16-byte unique identifier.
 * @param kdfVersion Version of KDF used to derive the KEK.
 * @returns Authenticated WrappedDEK structure ready for vault persistence.
 */
export function wrapDEK(
  kek: Uint8Array,
  dek: Uint8Array,
  keyId: Uint8Array,
  kdfVersion: number
): WrappedDEK {
  if (!kek || kek.length !== KEK_BYTE_LENGTH) {
    throw new GhostTagError({
      code: GhostTagErrorCode.ARGON2ID_FAILED,
      userMessage: `KEK must be ${KEK_BYTE_LENGTH} bytes.`,
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.ERROR,
    });
  }

  if (!dek || dek.length !== DEK_BYTE_LENGTH) {
    throw new GhostTagError({
      code: GhostTagErrorCode.ARGON2ID_FAILED,
      userMessage: `DEK must be ${DEK_BYTE_LENGTH} bytes.`,
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.ERROR,
    });
  }

  if (!keyId || keyId.length !== KEY_ID_BYTE_LENGTH) {
    throw new GhostTagError({
      code: GhostTagErrorCode.ARGON2ID_FAILED,
      userMessage: `keyId must be ${KEY_ID_BYTE_LENGTH} bytes.`,
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.ERROR,
    });
  }

  const aad = buildKeyWrapAAD(keyId, kdfVersion);
  const encrypted = encrypt(kek, dek, aad);

  return {
    keyId: bytesToHex(keyId),
    wrappedCiphertext: encrypted.ciphertext,
    nonce: encrypted.nonce,
    tag: encrypted.tag,
    creationTime: Date.now(),
    keyVersion: kdfVersion,
    status: KeyStatus.ACTIVE,
  };
}

/**
 * Unwraps an encrypted Data Encryption Key (DEK) using the active Key Encryption Key (KEK).
 *
 * Security Properties:
 * - AAD is reconstructed using the keyId and keyVersion stored in the WrappedDEK.
 * - If KEK is incorrect or ciphertext/tag has been modified, throws GCM_AUTH_FAILED.
 * - Guarantees the recovered DEK is exactly 32 bytes.
 *
 * @param kek 32-byte Key Encryption Key.
 * @param wrapped WrappedDEK record from vault.
 * @returns Plaintext 32-byte Data Encryption Key.
 * @throws {GhostTagError} If unwrapping or authentication fails.
 */
export function unwrapDEK(
  kek: Uint8Array,
  wrapped: WrappedDEK
): Uint8Array {
  if (!wrapped || !wrapped.keyId || !wrapped.wrappedCiphertext) {
    throw new GhostTagError({
      code: GhostTagErrorCode.GCM_AUTH_FAILED,
      userMessage: 'Key unwrapping failed: invalid wrapped DEK object.',
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.CRITICAL,
    });
  }

  let keyIdBytes: Uint8Array;
  try {
    keyIdBytes = hexToBytes(wrapped.keyId);
  } catch (err) {
    throw new GhostTagError({
      code: GhostTagErrorCode.GCM_AUTH_FAILED,
      userMessage: 'Key unwrapping failed: invalid hex keyId.',
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.CRITICAL,
      cause: err,
    });
  }

  if (keyIdBytes.length !== KEY_ID_BYTE_LENGTH) {
    throw new GhostTagError({
      code: GhostTagErrorCode.GCM_AUTH_FAILED,
      userMessage: `Key unwrapping failed: keyId length mismatch (expected ${KEY_ID_BYTE_LENGTH} bytes).`,
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.CRITICAL,
    });
  }

  const aad = buildKeyWrapAAD(keyIdBytes, wrapped.keyVersion);
  const dek = decrypt(
    kek,
    wrapped.wrappedCiphertext,
    wrapped.nonce,
    wrapped.tag,
    aad
  );

  if (dek.length !== DEK_BYTE_LENGTH) {
    throw new GhostTagError({
      code: GhostTagErrorCode.GCM_AUTH_FAILED,
      userMessage: `Unwrapped DEK length mismatch: expected ${DEK_BYTE_LENGTH} bytes, got ${dek.length}.`,
      category: ErrorCategory.CRYPTO,
      severity: ErrorSeverity.CRITICAL,
    });
  }

  return dek;
}

